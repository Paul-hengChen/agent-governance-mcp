test("AC3: on a schema 16 handoff (marker absent or present) the removed old-path steps are rejected with the docs/migration-v5.md hint", async () => {
  assert.equal(T.MIGRATION_HINT, MIGRATION);
  const steps = [
    ["pm", "In_Progress", "sr-engineer", "In_Progress"],
    ["code-reviewer", "In_Progress", "qa-engineer", "In_Progress"],
    ["qa-engineer", "In_Progress", "qa-engineer", "PASS"],
  ];
  for (const marker of [false, true]) {
    for (const [pa, ps, na, ns] of steps) {
      const ws = mkWs({ agent: pa, status: ps, marker }, { noNewTest: true });
      const extra = ns === "PASS" ? { qa_review: "x", review_task_ids: ["T-1"] } : {};
      const r = await upd(ws, na, ns, extra);
      const label = `${pa}:${ps} -> ${na}:${ns} (marker ${marker ? "present" : "absent"})`;
      assert.ok(rejected(r), `${label} must be rejected: ${text(r)}`);
      assert.ok(text(r).includes("docs/migration-v5.md"), `${label} hint names docs/migration-v5.md: ${text(r)}`);
    }
  }
});

test("AC3: a legal new-chain step is accepted and gets no migration hint; the hint keys on the step only", async () => {
  for (const marker of [false, true]) {
    const ws = mkWs({ agent: "pm", status: "In_Progress", marker });
    const r = await upd(ws, "qa-engineer", "In_Progress");
    assert.ok(!rejected(r), `pm -> qa-engineer is a legal step (marker ${marker}): ${text(r)}`);
    assert.ok(!text(r).includes("docs/migration-v5.md"), "no migration hint on a legal step");
  }
  const t = (agent, status) => ({ agent, status });
  assert.equal(T.oldPathStepHint(t("pm", "In_Progress"), t("qa-engineer", "In_Progress")), null);
  assert.equal(T.oldPathStepHint(t("architect", "In_Progress"), t("sr-engineer", "In_Progress")), PM_TO_SR("architect") + MIGRATION);
  assert.ok(T.oldPathStepHint(t("sr-engineer", "In_Progress"), t("qa-engineer", "FAIL"))?.endsWith(MIGRATION));
});

