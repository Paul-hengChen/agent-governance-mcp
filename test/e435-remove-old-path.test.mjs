test("AC9: SQLite mode rejects pm -> sr, qa PASS, qa completed_tasks and qa tw_complete_task; code-reviewer PASS accepted; no SQLite version added", async (t) => {
  assert.equal(CURRENT_VERSIONS.sqlite, 2, "no SQLite schema version added");
  if (!SqliteHandoffStorage) return t.skip("better-sqlite3 not installed");
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "e435-sq-"));
  const storage = new SqliteHandoffStorage(path.join(dir, "agc.db"));
  const run = async (entry, agent, args) => {
    await storage.writeState({ workspacePath: dir, activeFeature: F, status: "In_Progress", completedTasks: [], pendingNotes: ["seed"], lastAgent: agent });
    resetSession(dir); storage.readState(dir);
    return Promise.resolve().then(() => entry.run({ workspace_path: dir, ...args })).catch(asRejection);
  };
  const w = (agent, status, extra = {}) => ({ active_feature: F, status, agent_id: agent, completed_tasks: [], pending_notes: [], ...extra });
  try {
    setActiveStorage(storage);
    const s = await run(UPD, "pm", w("sr-engineer", "In_Progress"));
    assert.ok(rejected(s) && text(s).includes(PM_TO_SR("pm").trim()), `SQLite pm -> sr rejected with the hint: ${text(s)}`);
    const q = await run(UPD, "qa-engineer", w("qa-engineer", "PASS", { qa_review: "x", review_task_ids: ["T-1"] }));
    assert.ok(rejected(q) && text(q).includes(QA_PASS_MSG), `SQLite qa PASS rejected naming code-reviewer: ${text(q)}`);
    const l = await run(UPD, "sr-engineer", w("qa-engineer", "In_Progress", { completed_tasks: ["T-1"] }));
    assert.match(text(l), /NON_JUDGE_COMPLETED_TASKS_REJECTED/);
    const c = await run(COMPLETE, "sr-engineer", { task_id: "T-1", agent_id: "qa-engineer" });
    assert.ok(text(c).includes(COMPLETE_BLOCKED), `SQLite qa tw_complete_task blocked: ${text(c)}`);
    const p = await run(UPD, "code-reviewer", w("code-reviewer", "PASS", { review_verdict: "APPROVED", qa_review: "judged", review_task_ids: ["T-1"] }));
    assert.ok(!rejected(p), `SQLite code-reviewer PASS accepted with no marker: ${text(p)}`);
  } finally {
    setActiveStorage(new FileHandoffStorage());
    try { storage.close(); } catch {}
  }
});
