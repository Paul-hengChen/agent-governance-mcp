test("AC7: no composed prompt, hook output or shipped template describes qa-engineer as the closing role or names chain_path", () => {
  const ws = fs.mkdtempSync(path.join(os.tmpdir(), "e435-ac7-"));
  fs.mkdirSync(path.join(ws, ".current"), { recursive: true });
  const sources = [];
  for (const p of PROMPT_REGISTRY) {
    const r = buildPromptForRole(p.skillFile, p.description, ws);
    sources.push([`prompt ${p.name}`, r.messages.map((m) => m.content.text).join("\n")]);
  }
  const hook = execFileSync("node", [path.join(ROOT, "bin", "agent-governance-context.mjs")], {
    env: { ...process.env, CLAUDE_PROJECT_DIR: ws, AGC_SERVER_ROOT: ROOT }, encoding: "utf-8",
  });
  sources.push(["SessionStart hook", JSON.parse(hook).hookSpecificOutput.additionalContext]);
  for (const dir of ["agent-adapters", "claude-code-agents"]) {
    for (const f of fs.readdirSync(path.join(ROOT, "templates", dir))) sources.push([`templates/${dir}/${f}`, fs.readFileSync(path.join(ROOT, "templates", dir, f), "utf-8")]);
  }
  const hits = [];
  for (const [name, body] of sources) for (const re of OLD_PATH) if (re.test(body)) hits.push(`${name}: ${re}`);
  assert.deepEqual(hits, []);
});

