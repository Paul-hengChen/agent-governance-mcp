const DESC = {
  status: 'Execution status. status="PASS" requires agent_id="code-reviewer", the chain\'s judge; any other agent_id is rejected at the tool boundary.',
  completed_tasks: 'Task ids the judge has completed for this feature. Only agent_id "code-reviewer" may grow it; a non-empty list from any other agent_id is rejected (NON_JUDGE_COMPLETED_TASKS_REJECTED). File mode: a code-reviewer list is added to the ids already recorded; kept across same-feature writes that omit it or pass []; the code-reviewer\'s FAIL write removes its review_task_ids; cleared when active_feature changes. SQLite: stored as given.',
  tw_complete_task: 'Mark task completed [x]. Reserved for code-reviewer, the chain\'s judge — pass agent_id="code-reviewer".',
};

// A schema 16 handoff as the pre-E435 writer emitted it (captured from dist/ at base a1a36b2, frozen here).
function v16Handoff({ agent, status, marker = false, extra = "" }) {
  return [
    "---", "schema_version: 16", `active_feature: "${F}"`, `status: "${status}"`,
    'last_updated: "2026-01-01T00:00:00.123Z"', `last_agent: "${agent}"`, "cut_approved: true",
    'scope_decision: "single-feature"', ...(marker ? ['chain_path: "test-first"'] : []), ...(extra ? [extra] : []),
    "qa_round: 2", "review_round: 0", "visual_round: 0", "hop_count: 0", "qa_rounds_total: 3",
    "review_rounds_total: 0", "visual_rounds_total: 0", "---", "# Handoff State", "", "## Completed", "- (none)", "",
    "## Pending & Handoff Notes", "- seed", "", "---",
    "> System Note: Auto-generated by agent-governance-mcp. Do NOT edit manually.", "",
  ].join("\n");
}


const text = (r) => r?.content?.[0]?.text ?? "";
const rejected = (r) => Boolean(r?.isError) || text(r).startsWith("⛔") || text(r).startsWith("❌");
// A zod failure throws; surface it as the rejection a client sees.
const asRejection = (err) => ({ isError: true, content: [{ type: "text", text: `⛔ ${err.message}` }] });
const hpath = (ws) => resolveCurrentLanePaths(ws).handoffPath;
const state = (ws) => new FileHandoffStorage().parse(ws);

function mkWs(seed, { noNewTest = false } = {}) {
  const ws = fs.mkdtempSync(path.join(os.tmpdir(), "e435-"));
  fs.mkdirSync(path.dirname(hpath(ws)), { recursive: true });
  if (seed) fs.writeFileSync(hpath(ws), v16Handoff(seed));
  if (noNewTest) {
    fs.mkdirSync(path.join(ws, "qa_reports"), { recursive: true });
    fs.writeFileSync(path.join(ws, "qa_reports", `no-new-test_${F}.txt`), "no new test\n");
  }
  return ws;
}

function fresh(ws) {
  setActiveStorage(new FileHandoffStorage());
  forceSeedStampIfExists(ws); resetSession(ws); markStateRead(ws);
}

async function call(entry, ws, args) {
  fresh(ws);
  return Promise.resolve().then(() => entry.run({ workspace_path: ws, ...args })).catch(asRejection);
}
const upd = (ws, agent, status, extra = {}) =>
  call(UPD, ws, { active_feature: F, status, agent_id: agent, completed_tasks: [], pending_notes: [], ...extra });

// ---------------------------------------------------------------- AC1

test("AC1: pm:In_Progress -> sr-engineer:In_Progress is rejected on every dispatch_mode, even with a no-new-test record; the hint names qa-engineer", async () => {
  for (const extra of ["", 'dispatch_mode: "feature"', 'dispatch_mode: "bugfix"']) {
    const ws = mkWs({ agent: "pm", status: "In_Progress", extra }, { noNewTest: true });
    const r = await upd(ws, "sr-engineer", "In_Progress");
    assert.ok(rejected(r), `pm -> sr must be rejected (${extra || "no dispatch_mode"}): ${text(r)}`);
    assert.match(text(r), /TRANSITION_REJECTED/);
    assert.ok(text(r).includes(PM_TO_SR("pm").trim()), `hint names qa-engineer as the build entry: ${text(r)}`);
  }
});

// ---------------------------------------------------------------- AC2

test("AC2: qa-engineer status=PASS is rejected and the message names code-reviewer as the judge", async () => {
  assert.equal(T.QA_PASS_REFINE_MESSAGE, QA_PASS_MSG);
  const ws = mkWs({ agent: "qa-engineer", status: "In_Progress" });
  const before = fs.readFileSync(hpath(ws), "utf-8");
  const r = await upd(ws, "qa-engineer", "PASS", { qa_review: "x", review_task_ids: ["T-1"] });
  assert.ok(rejected(r), "qa-engineer PASS must be rejected");
  assert.ok(text(r).includes(QA_PASS_MSG), `message names code-reviewer + migration note: ${text(r)}`);
  assert.equal(fs.readFileSync(hpath(ws), "utf-8"), before, "no state written");
});

test("AC2: qa-engineer cannot complete tasks: tw_complete_task and a non-empty completed_tasks are both rejected", async () => {
  const ws = mkWs({ agent: "sr-engineer", status: "In_Progress" });
  await call(ADD, ws, { task_id: "T-1", description: "one" });
  const c = await call(COMPLETE, ws, { task_id: "T-1", agent_id: "qa-engineer" });
  assert.ok(text(c).includes(COMPLETE_BLOCKED), `tw_complete_task by qa-engineer blocked: ${text(c)}`);
  assert.ok(text(c).includes(MIGRATION.trim()), "qa-engineer caller gets the migration hint");
  const u = await upd(ws, "qa-engineer", "In_Progress", { completed_tasks: ["T-1"] });
  assert.ok(rejected(u), "qa-engineer completed_tasks must be rejected");
  assert.match(text(u), /NON_JUDGE_COMPLETED_TASKS_REJECTED/);
});

test("AC2: code-reviewer completes tasks, grows completed_tasks and writes PASS with no marker on the handoff", async () => {
  const ws = mkWs({ agent: "code-reviewer", status: "In_Progress" });
  await call(ADD, ws, { task_id: "T-1", description: "one" });
  const c = await call(COMPLETE, ws, { task_id: "T-1", agent_id: "code-reviewer" });
  assert.match(text(c), /"success":true/, `code-reviewer tw_complete_task accepted: ${text(c)}`);
  const r = await upd(ws, "code-reviewer", "PASS", {
    review_verdict: "APPROVED", qa_review: "judged", review_task_ids: ["T-1"], completed_tasks: ["T-1"],
  });
  assert.ok(!rejected(r), `unmarked code-reviewer PASS accepted: ${text(r)}`);
  const s = state(ws);
  assert.deepEqual([s.status, s.last_agent, s.completed_tasks], ["PASS", "code-reviewer", ["T-1"]]);
});

