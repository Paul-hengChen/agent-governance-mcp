const MIGRATION = " If this feature started on the pre-v5 chain, docs/migration-v5.md says how to finish or restart it.";
const QA_PASS_MSG = `status="PASS" requires agent_id="code-reviewer": code-reviewer is the judge; qa-engineer writes tests and never writes PASS.${MIGRATION}`;
const PM_TO_SR = (a) => ` The build entry is qa-engineer: hand off ${a}:In_Progress → qa-engineer:In_Progress; qa-engineer writes the scenario tests, or records that the ticket needs no new test, before sr-engineer builds.`;
